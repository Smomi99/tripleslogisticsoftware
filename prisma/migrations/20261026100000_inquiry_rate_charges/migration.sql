-- selects a container they can also select which charges to add. If any extra
-- charge is needed they can add a new one. Including the charges, the quoted
-- price will update."
-- ===========================================================================
--
-- Changed:
--
--   inquiry_rate          + freight_price, the line's sell price as attached.
--                           quoted_price now means freight_price plus the
--                           charges below. Every existing row has no charges,
--                           so it is backfilled from quoted_price and its
--                           quoted figure does not move.
--                         + UNIQUE (tenant_id, id), the composite target the
--                           new table's tenant-safe key needs (§4 rule 10).
--
-- New:
--
--   inquiry_rate_charge   the charges an attached container carries: the
--                         purchase rate's local charges that were ticked, and
--                         any extra typed on the inquiry.
--
-- The DDL was generated by `prisma migrate diff`, with freight_price added in
-- three steps so existing rows can be backfilled; the integrity, tenancy and
-- audit statements are hand-written.
-- ===========================================================================

