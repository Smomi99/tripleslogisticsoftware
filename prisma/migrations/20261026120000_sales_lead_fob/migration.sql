-- ----------------------------------------------------------------- backfill
-- The day each existing lead was recorded, as the workspace reads the clock.
UPDATE "sales_lead" l
   SET "lead_date" = (l."created_at" AT TIME ZONE COALESCE(t."timezone", 'Asia/Dhaka'))::date
  FROM "tenant" t
 WHERE t."id" = l."tenant_id";

