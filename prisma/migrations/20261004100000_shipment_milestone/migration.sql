-- ---------------------------------------------------------------- integrity
-- One live confirmation per booking per kind. A correction updates the row;
-- the partial index leaves room for a retired one to be kept.
CREATE UNIQUE INDEX "shipment_milestone_one_live_key"
  ON "shipment_milestone"("tenant_id", "shipment_id", "kind")
  WHERE "deleted_at" IS NULL;

-- A reason, when given, says something.
ALTER TABLE "shipment_milestone" ADD CONSTRAINT "shipment_milestone_reason_not_blank"
  CHECK ("change_reason" IS NULL OR length(btrim("change_reason")) > 0);

