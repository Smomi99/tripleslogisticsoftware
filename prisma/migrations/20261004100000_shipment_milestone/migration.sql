-- One new table and one enum. shipment_milestone holds the three
-- confirmations of the client's `Depart-Arrival Landing page`: On board
-- (DEPARTED), Transshipment (TRANSSHIPPED, indirect routes only) and Arrival
-- (ARRIVED), one live row per booking per kind.
--
-- Nothing existing is altered. bl_draft.laden_on_board_date is written by the
-- API when a departure is confirmed; the column already exists.
