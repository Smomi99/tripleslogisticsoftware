-- ===========================================================================
-- BUSINESS SETTINGS — Settings → Business Settings (owner request, 2026-11-17)
-- ===========================================================================
--
-- "A business setting on the setting page where we add business name, address
-- and the other things needed — we print lots of things, and the business name
-- and the rest should come from here."
--
-- One new table, business_profile: one row per workspace, holding what prints
-- at the head of a document — name, logo, address, phone, email, website, BIN,
-- TIN and trade licence. Nothing existing is altered: tenant.name and
-- tenant.logo_file stay as the platform's record of the account, and are the
-- letterhead's fallback until a workspace saves this screen.
--
-- The DDL was generated by `prisma migrate diff`; the integrity, tenancy,
-- audit and permission statements below it are hand-written.
-- ===========================================================================

-- CreateTable
CREATE TABLE "business_profile" (
    "tenant_id" BIGINT NOT NULL,
    "id" BIGSERIAL NOT NULL,
    "business_name" VARCHAR(200) NOT NULL,
    "address" TEXT,
    "phone" VARCHAR(100),
    "email" VARCHAR(320),
    "website" VARCHAR(200),
    "bin_no" VARCHAR(50),
    "tin_no" VARCHAR(50),
    "trade_licence_no" VARCHAR(50),
    "logo_file" VARCHAR(500),
    "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ(6) NOT NULL,
    "created_by" BIGINT,
    "updated_by" BIGINT,

    CONSTRAINT "business_profile_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
CREATE UNIQUE INDEX "business_profile_tenant_id_key" ON "business_profile"("tenant_id");

-- AddForeignKey
ALTER TABLE "business_profile" ADD CONSTRAINT "business_profile_tenant_id_fkey" FOREIGN KEY ("tenant_id") REFERENCES "tenant"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- AddForeignKey
ALTER TABLE "business_profile" ADD CONSTRAINT "business_profile_created_by_fkey" FOREIGN KEY ("created_by") REFERENCES "user"("id") ON DELETE RESTRICT ON UPDATE CASCADE;

-- AddForeignKey
ALTER TABLE "business_profile" ADD CONSTRAINT "business_profile_updated_by_fkey" FOREIGN KEY ("updated_by") REFERENCES "user"("id") ON DELETE RESTRICT ON UPDATE CASCADE;


-- ---------------------------------------------------------------- integrity
-- A letterhead with no name is not a letterhead.
ALTER TABLE "business_profile" ADD CONSTRAINT "business_profile_name_not_blank"
  CHECK (length(btrim("business_name")) > 0);

-- ------------------------------------------------------------------ tenancy
ALTER TABLE "business_profile" ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON "business_profile"
  USING (tenant_id = app_staff_tenant())
  WITH CHECK (tenant_id = app_staff_tenant());

-- No DELETE: the row is the workspace's, and a cleared field is an UPDATE.
GRANT SELECT, INSERT, UPDATE ON TABLE "business_profile" TO ff_app;
GRANT USAGE, SELECT ON SEQUENCE "business_profile_id_seq" TO ff_app;

-- §4 rule 7: the audit trail is a trigger, so a write from any path is caught.
CREATE TRIGGER "business_profile_audit"
  AFTER INSERT OR UPDATE OR DELETE ON "business_profile"
  FOR EACH ROW EXECUTE FUNCTION app_audit_row();

-- -------------------------------------------------------------- permissions
-- Shipped with the migration rather than left to `db:seed`, so a deploy that
-- adds the screen also adds the rights that guard it. The seed upserts the
-- same rows from the same code constant, so running it afterwards is a no-op.
INSERT INTO "permission" ("module", "feature", "action", "key", "updated_at")
VALUES
  ('SETTING', 'SETTING.BUSINESS', 'VIEW', 'SETTING.BUSINESS.VIEW', CURRENT_TIMESTAMP),
  ('SETTING', 'SETTING.BUSINESS', 'EDIT', 'SETTING.BUSINESS.EDIT', CURRENT_TIMESTAMP)
ON CONFLICT ("key") DO NOTHING;

-- A role that already maintains the company's sign-off and its Air Waybill
-- issuer lines (Settings → Notifications) maintains these too: the same
-- address and licence numbers, now in one place. Nobody gains a right over
-- anything they could not already change; everyone else is granted it on the
-- Roles matrix. A superadmin needs no grant (§7 rule 1).
INSERT INTO "role_permission" ("tenant_id", "role_id", "permission_id", "created_at")
SELECT n."tenant_id", n."role_id", p."id", now()
  FROM "role_permission" n
  JOIN "permission" nv ON nv."id" = n."permission_id" AND nv."key" = 'SETTING.NOTIFICATION.VIEW'
  JOIN "permission" p ON p."key" = 'SETTING.BUSINESS.VIEW'
ON CONFLICT ("tenant_id", "role_id", "permission_id") DO NOTHING;

INSERT INTO "role_permission" ("tenant_id", "role_id", "permission_id", "created_at")
SELECT n."tenant_id", n."role_id", p."id", now()
  FROM "role_permission" n
  JOIN "permission" ne ON ne."id" = n."permission_id" AND ne."key" = 'SETTING.NOTIFICATION.EDIT'
  JOIN "permission" p ON p."key" = 'SETTING.BUSINESS.EDIT'
ON CONFLICT ("tenant_id", "role_id", "permission_id") DO NOTHING;
