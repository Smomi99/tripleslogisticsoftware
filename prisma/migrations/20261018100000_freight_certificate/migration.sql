-- ---------------------------------------------------------------- integrity
-- One live certificate per debit invoice. Partial, so a certificate retired
-- by soft delete does not hold the invoice forever.
CREATE UNIQUE INDEX "freight_certificate_one_live_key"
  ON "freight_certificate"("tenant_id", "debit_invoice_id")
  WHERE "deleted_at" IS NULL;

-- A dollar figure is never negative, and a rate is something to divide by.
ALTER TABLE "freight_certificate" ADD CONSTRAINT "freight_certificate_amount_non_negative"
  CHECK ("amount" >= 0);
ALTER TABLE "freight_certificate" ADD CONSTRAINT "freight_certificate_rate_positive"
  CHECK ("conversion_rate" > 0);

-- ------------------------------------------------------------------ tenancy
-- Staff only, as every accounts table: app_staff_tenant() is NULL for an
-- agent or a customer session, so neither portal can read a certificate.
ALTER TABLE "freight_certificate" ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON "freight_certificate"
  USING (tenant_id = app_staff_tenant())
  WITH CHECK (tenant_id = app_staff_tenant());

-- No DELETE: §4 rule 3.
GRANT SELECT, INSERT, UPDATE ON TABLE "freight_certificate" TO ff_app;
GRANT USAGE, SELECT ON SEQUENCE "freight_certificate_id_seq" TO ff_app;

-- §4 rule 7: the audit trail is a trigger, so a write from any path is caught.
CREATE TRIGGER "freight_certificate_audit"
  AFTER INSERT OR UPDATE OR DELETE ON "freight_certificate"
  FOR EACH ROW EXECUTE FUNCTION app_audit_row();

-- §4 rule 10. Currency is system-capable and reached by a single-column key,
-- so the constraint alone cannot say whose row it is.
CREATE TRIGGER freight_certificate_currency_id_tenant_guard
  BEFORE INSERT OR UPDATE OF currency_id ON freight_certificate
  FOR EACH ROW EXECUTE FUNCTION app_assert_parent_tenant('currency', 'currency_id');

