-- One new table:
--
--   freight_certificate   one letter certifying what the freight on a shipment
--                         cost: the shipment facts as printed, the shipper's
--                         invoice, EXP and LC/TT/Sales Contract numbers (held
--                         nowhere else), and the invoice total in US dollars
--
-- And one new permission feature, ACCOUNTS.FREIGHT_CERTIFICATE.
--
-- Nothing existing is altered. The DDL was generated by `prisma migrate diff`;
-- the integrity, tenancy and audit statements below it are hand-written.
-- ===========================================================================

-- CreateTable
CREATE TABLE "freight_certificate" (
    "tenant_id" BIGINT NOT NULL,
    "id" BIGSERIAL NOT NULL,
    "code" VARCHAR(32) NOT NULL,
    "series_year" INTEGER NOT NULL,
    "debit_invoice_id" BIGINT NOT NULL,
    "certificate_date" DATE NOT NULL,
    "shipper_text" TEXT NOT NULL,
    "packages" TEXT,
    "commodity" TEXT,
    "commercial_invoice_no" VARCHAR(100),
    "commercial_invoice_date" DATE,
    "exp_no" VARCHAR(100),
    "exp_date" DATE,
    "bl_no" VARCHAR(64),
    "lc_no" VARCHAR(200),
    "port_of_loading" TEXT,
    "port_of_delivery" TEXT,
    "currency_id" BIGINT NOT NULL,
    "amount" DECIMAL(18,4) NOT NULL,
    "conversion_rate" DECIMAL(18,10) NOT NULL,
    "is_active" BOOLEAN NOT NULL DEFAULT true,
    "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ(6) NOT NULL,
    "created_by" BIGINT,
    "updated_by" BIGINT,
    "deleted_at" TIMESTAMPTZ(6),

    CONSTRAINT "freight_certificate_pkey" PRIMARY KEY ("id")
);

