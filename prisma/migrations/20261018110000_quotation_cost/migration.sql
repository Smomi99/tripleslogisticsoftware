-- ---------------------------------------------------------------- integrity
-- A block is owed to exactly the party its type names (debit_invoice_cost's rule).
ALTER TABLE "quotation_cost" ADD CONSTRAINT "quotation_cost_party_matches_type"
  CHECK (
    ("party_type" = 'CARRIER' AND "carrier_id" IS NOT NULL AND "agent_id" IS NULL AND "vendor_id" IS NULL) OR
    ("party_type" = 'AGENT'   AND "agent_id"   IS NOT NULL AND "carrier_id" IS NULL AND "vendor_id" IS NULL) OR
    ("party_type" = 'VENDOR'  AND "vendor_id"  IS NOT NULL AND "carrier_id" IS NULL AND "agent_id" IS NULL)
  );

ALTER TABLE "quotation_cost" ADD CONSTRAINT "quotation_cost_rate_positive"
  CHECK ("conversion_rate" > 0);

ALTER TABLE "quotation_cost_line" ADD CONSTRAINT "quotation_cost_line_quantity_non_negative"
  CHECK ("quantity" >= 0);

-- ------------------------------------------------------------------ tenancy
-- Staff only, like the quotation itself: neither portal ever reads a buy price.
