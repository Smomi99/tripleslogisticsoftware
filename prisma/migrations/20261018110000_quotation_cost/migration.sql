-- -------------------------------------------------------------- permission
-- Column-level, like DEBIT_INVOICE.VIEW_BUY_PRICE: who may read a quotation and
-- who may read what the forwarder pays for it are separate grants.
INSERT INTO "permission" ("module", "feature", "action", "key", "updated_at")
VALUES
  ('CUSTOMER_SERVICE', 'CUSTOMER_SERVICE.QUOTATION', 'VIEW_BUY_PRICE',
   'CUSTOMER_SERVICE.QUOTATION.VIEW_BUY_PRICE', CURRENT_TIMESTAMP)
ON CONFLICT ("key") DO NOTHING;

-- A role already trusted with buy prices on the debit invoice, that can also
-- open quotations, sees them on the quotation too. Nobody gains a figure they
-- could not already read; everyone else is granted it on the Roles matrix.
INSERT INTO "role_permission" ("tenant_id", "role_id", "permission_id", "created_at")
SELECT q."tenant_id", q."role_id", p."id", now()
  FROM "role_permission" q
  JOIN "permission" qv ON qv."id" = q."permission_id" AND qv."key" = 'CUSTOMER_SERVICE.QUOTATION.VIEW'
  JOIN "role_permission" b ON b."tenant_id" = q."tenant_id" AND b."role_id" = q."role_id"
  JOIN "permission" bv ON bv."id" = b."permission_id" AND bv."key" = 'ACCOUNTS.DEBIT_INVOICE.VIEW_BUY_PRICE'
  JOIN "permission" p ON p."key" = 'CUSTOMER_SERVICE.QUOTATION.VIEW_BUY_PRICE'
ON CONFLICT ("tenant_id", "role_id", "permission_id") DO NOTHING;
