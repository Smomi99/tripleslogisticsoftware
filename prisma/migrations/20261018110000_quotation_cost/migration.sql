-- have cost details. We want the same functionality on the quotation, and on
-- the debit note the cost details will pull from the quotation."
-- ===========================================================================
--
-- Two new tables, the debit invoice's cost side again, on a quotation:
--
--   quotation_cost        one "Buying from Carrier / Agent / Vendor" block
--   quotation_cost_line   that block's grid
--
-- Internal only: never printed, never sent. Saved on their own route, so
-- changing what the forwarder expects to pay never issues the customer a new
-- revision.
--
-- And one new permission: CUSTOMER_SERVICE.QUOTATION.VIEW_BUY_PRICE.
--
-- Nothing existing is altered. The DDL was generated by `prisma migrate diff`
-- (with quotation_cost_line.amount made GENERATED by hand, as Prisma cannot
-- express it); the integrity, tenancy and audit statements are hand-written.
-- ===========================================================================

