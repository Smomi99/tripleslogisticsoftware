-- Five new tables, three new enums, and two new shipment statuses.
--
--   shipment_advise        one per booking (§3.1) — the document, and where the
--                          House BL number is allocated (§3.3)
--   shipment_advise_line   the PO grid, snapshotted from the CLP (§3.2)
--   bl_draft               the bill of lading, staff and customer alike (§3.6)
--   bl_draft_container     the Marks and Numbers block, pulled from the CLPs
--   bl_template            Make Templet / Use Templet (§3.5)
--
-- shipment_status gains ADVISED and BL_DRAFTED (§3.8). Both worklists are
-- bookings narrowed by status, like every other worklist in the product, and
-- the machine stopped at CARGO_RECEIVED — finalising a CLP moves nothing.
--
-- The DDL below was generated by `prisma migrate diff` and then reduced to the
-- statements belonging to this change. The generator also emits a backlog of
-- pre-existing drift — 48 RenameForeignKey, 12 DropIndex, 11 RenameIndex and
-- 10 updated_at default changes against tables this module does not touch —
-- which is deliberately NOT included here. Sweeping it up in a feature
-- migration would hide a schema change nobody reviewed inside one they did.
-- ===========================================================================

