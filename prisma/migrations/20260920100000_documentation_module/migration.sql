-- One live advise per booking (§3.1). Partial, so a cancelled-and-soft-deleted
-- advise does not reserve the booking forever — the same reason port_code's
-- unique index is partial (CR-002).
CREATE UNIQUE INDEX "shipment_advise_tenant_id_shipment_id_live_key"
  ON "shipment_advise" ("tenant_id", "shipment_id")
  WHERE "deleted_at" IS NULL AND "status" <> 'CANCELLED';

-- One live BL draft per booking. §3.6 makes the customer's copy and the staff
-- copy the same document in different states, so two live rows for one booking
-- would be exactly the split that decision refuses.
CREATE UNIQUE INDEX "bl_draft_tenant_id_shipment_id_live_key"
  ON "bl_draft" ("tenant_id", "shipment_id")
  WHERE "deleted_at" IS NULL AND "status" <> 'CANCELLED';

