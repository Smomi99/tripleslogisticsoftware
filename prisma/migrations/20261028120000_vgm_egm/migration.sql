-- ---------------------------------------------------------------- integrity
-- One live VGM per container; saving again updates it.
CREATE UNIQUE INDEX "vgm_one_live_key"
  ON "vgm"("tenant_id", "clp_id")
  WHERE "deleted_at" IS NULL;

ALTER TABLE "vgm" ADD CONSTRAINT "vgm_text_not_blank"
  CHECK (length(btrim("carrier_booking_no")) > 0 AND length(btrim("signatory_name")) > 0);

-- The VGM is the packed container's weight with the cargo in it, so it is
-- more than nothing and never less than the cargo alone.
ALTER TABLE "vgm" ADD CONSTRAINT "vgm_weights_ck"
  CHECK (
    "vgm_kg" > 0
    AND ("gross_weight_kg" IS NULL OR ("gross_weight_kg" >= 0 AND "vgm_kg" >= "gross_weight_kg"))
  );

-- ------------------------------------------------------------------ tenancy
ALTER TABLE "vgm" ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON "vgm"
  USING (tenant_id = app_staff_tenant())
  WITH CHECK (tenant_id = app_staff_tenant());

ALTER TABLE "egm_document" ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON "egm_document"
  USING (tenant_id = app_staff_tenant())
  WITH CHECK (tenant_id = app_staff_tenant());

