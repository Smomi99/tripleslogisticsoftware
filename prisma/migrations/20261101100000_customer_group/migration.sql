-- ---------------------------------------------------------------- integrity
ALTER TABLE "customer_group" ADD CONSTRAINT "customer_group_name_not_blank"
  CHECK (length(btrim("name")) > 0);

-- One live group of a name per workspace, whatever its case.
CREATE UNIQUE INDEX "customer_group_name_live_key"
  ON "customer_group"("tenant_id", lower(btrim("name")))
  WHERE "deleted_at" IS NULL;

-- A customer is in a group once.
CREATE UNIQUE INDEX "customer_group_member_live_key"
  ON "customer_group_member"("tenant_id", "customer_group_id", "customer_id")
  WHERE "deleted_at" IS NULL;

-- ------------------------------------------------------------------ tenancy
